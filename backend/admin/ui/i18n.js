let current = 'tr';
try {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === 'en' || stored === 'tr') current = stored;
} catch {
  /* storage may be unavailable; keep the default */
}

const listeners = new Set();

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (lang !== 'tr' && lang !== 'en') return;
  if (lang === current) return;
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = lang;
  listeners.forEach((fn) => fn(lang));
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

function lookup(lang, key) {
  const parts = key.split('.');
  let node = dict[lang];
  for (const p of parts) {
    if (node == null || typeof node !== 'object') return undefined;
    node = node[p];
  }
  return typeof node === 'string' ? node : undefined;
}

/** Translate a dotted key with optional {placeholders}. */
export function t(key, vars) {
  let s = lookup(current, key);
  if (s === undefined) s = lookup('en', key);
  if (s === undefined) return key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split('{' + k + '}').join(String(v));
    }
  }
  return s;
}

/** Localized-string fallback rule (ARCHITECTURE §3) for an explicit language. */
export function L(ls, lang = current) {
  if (!ls) return '';
  const primary = (ls[lang] || '').trim();
  if (primary) return primary;
  const other = lang === 'tr' ? 'en' : 'tr';
  return (ls[other] || '').trim();
}

const dateFormatters = {};

/** Format an RFC 3339 timestamp for the given language ("" when unset). */
export function formatDate(iso, lang = current, withTime = true) {
  if (!iso) return '';
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return '';
  const key = lang + (withTime ? ':t' : ':d');
  if (!dateFormatters[key]) {
    dateFormatters[key] = new Intl.DateTimeFormat(lang === 'tr' ? 'tr-TR' : 'en-GB', {
      day: 'numeric',
      month: withTime ? 'short' : 'long',
      year: 'numeric',
      ...(withTime ? { hour: '2-digit', minute: '2-digit' } : {}),
    });
  }
  return dateFormatters[key].format(d);
}

document.documentElement.lang = current;

/** Translate for an explicit language (used by the phone preview, whose
 *  TR/EN toggle is independent from the panel language). */
export function tl(lang, key, vars) {
  const saved = current;
  current = lang === 'en' ? 'en' : 'tr';
  try {
    return t(key, vars);
  } finally {
    current = saved;
  }
}
